// Generates src/lib/i18n/resources.gen.ts from src/locales/es/*.json so that t() keys are typed
// without a hand-edited central file (one namespace file per feature, no shared es.json).
import { mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const localesDir = path.join(root, 'src/locales/es');
const outFile = path.join(root, 'src/lib/i18n/resources.gen.ts');

const namespaces = readdirSync(localesDir)
  .filter((file) => file.endsWith('.json'))
  .map((file) => path.basename(file, '.json'))
  .sort();

const entries = namespaces.map(
  (ns) => `  ${JSON.stringify(ns)}: typeof import('../../locales/es/${ns}.json');`,
);

const content = `// Generated by scripts/generate-i18n-types.mjs. Do not edit, do not commit.
export interface EsResources {
${entries.join('\n')}
}
`;

mkdirSync(path.dirname(outFile), { recursive: true });
writeFileSync(outFile, content);
